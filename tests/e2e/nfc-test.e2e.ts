import {test} from '@e2e-dev/mobile';
import {expect} from 'e2e';
const button=(screen:any,label:string)=>screen.getByRole('group').filter({hasText:label,has:screen.getByRole('button')}).last().getByRole('button');

test('NFC assistant uses the light app design and cancels its temporary pairing',{timeout:120_000},async({screen,device,app})=>{
 await device.openApp('de.phoenix.simulator',{relaunch:true});
 await screen.getByRole('button',{name:'Einstellungen',exact:true}).tap();
 await screen.getByTestId('settings-nfc-test').tap();
 await expect(screen.getByTestId('nfc-test-screen')).toBeVisible();
 await expect(screen.getByText('So funktioniert’s',{exact:true})).toBeVisible();
 await expect(screen.getByText('Patchbedarf nicht bestimmbar – Test ausstehend.',{exact:true})).toBeVisible();
 await expect(screen.getByTestId('nfc-test-create')).toBeVisible();
 const codeJoin=screen.getByTestId('nfc-test-code-join').getByRole('button');
 await screen.scrollUntilVisible(codeJoin);
 await codeJoin.tap();
 const connect=screen.getByRole('group').filter({hasText:'Verbinden',has:screen.getByRole('button')}).last();
 await expect(connect).toBeDisabled();
 await screen.getByRole('textbox').fill('123');
 await expect(screen.getByRole('textbox')).toHaveValue('123');
 await expect(connect).toBeDisabled();
 await screen.getByRole('textbox').fill('000001');
 await expect(connect).toBeEnabled();
 await app.back();
 await expect(screen.getByRole('textbox')).toHaveValue('000001');
 await button(screen,'Abbrechen').tap();
 await app.screenshot('nfc-test-intro-light');
 await screen.scrollUntilVisible(screen.getByTestId('nfc-test-create'));
 await screen.getByTestId('nfc-test-create').getByRole('button').tap();
 await expect(screen.getByTestId('nfc-test-qr')).toBeVisible({timeout:30_000});
 await expect(screen.getByTestId('nfc-pair-code')).toBeVisible();
 await screen.getByRole('button',{name:'Zurück zu Einstellungen',exact:true}).tap();
 await expect(screen.getByText('NFC-Test beenden?',{exact:true})).toBeVisible();
 await button(screen,'Weiter testen').tap();
 await expect(screen.getByTestId('nfc-test-qr')).toBeVisible();
 await screen.swipe({direction:'down',momentum:'slow'});
 await button(screen,'Verbindung trennen').tap();
 await expect(screen.getByText('Verbindung getrennt · Kopplungsdaten verworfen',{exact:true})).toBeVisible();
 await app.screenshot('nfc-test-disconnected-light');
 await button(screen,'Neuen Test vorbereiten').tap();
 await expect(screen.getByText('So funktioniert’s',{exact:true})).toBeVisible();
 await screen.getByRole('button',{name:'Zurück zu Einstellungen',exact:true}).tap();
 await expect(screen.getByTestId('settings-nfc-test')).toBeVisible();
});
